    def test_waf_detection(self, url, session=None) -> dict:
        """Verify WAF detection with triggered requests."""
        test_payloads = [
            ("GET", "/?id=1'+OR+1=1--", "SQLi"),
            ("GET", "/?q=<script>alert(1)</script>", "XSS"),
            ("GET", "/../../../etc/passwd", "Path Traversal"),
        ]

        triggered = []

        for method, path, attack_type in test_payloads:
            try:
                test_url = url.rstrip("/") + path
                resp_obj = session.get(test_url, timeout=10, allow_redirects=False, verify=False)
                resp = self._make_simple_response(resp_obj)

                if resp.status_code in [403, 406, 429, 503]:
                    triggered.append({
                        "attack": attack_type,
                        "status": resp.status_code,
                        "blocked": True,
                    })
            except Exception as e:
                logging.exception("Operation failed")
                continue

        return {
            "waf_detected": len(triggered) > 0,
            "blocked_attacks": triggered,
            "bypass_recommended": len(triggered) >= 2,
        }