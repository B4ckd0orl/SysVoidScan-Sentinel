@dataclass
class WAFInfo:
    name: str = "None"
    vendor: str = ""
    version: str = ""
    confidence: float = 0.0
    detected_by: str = ""
    bypass_techniques: list = None

    def __post_init__(self):
        if self.bypass_techniques is None:
            self.bypass_techniques = []


