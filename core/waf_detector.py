    def __init__(self, http_engine=None):
        self._http = http_engine

    def detect(self, url, session=None) -> WAFInfo:
        """Detect which WAF is protecting the target (synchronous)."""
        try:
            resp_obj = session.get(url, timeout=10, allow_redirects=False, verify=False)
            resp = self._make_simple_response(resp_obj)
        except Exception:
            return WAFInfo(name="None", confidence=0.0)

        for waf_name, signatures in self.WAF_SIGNATURES.items():
            confidence = 0.0
            detected_by = ""

            for header_pattern in signatures["headers"]:
                for resp_header in resp.headers:
                    if header_pattern.lower() in resp_header.lower():
                        confidence += 0.4
                        detected_by = f"header:{resp_header}"
                        break

            for cookie_pattern in signatures["cookies"]:
                for cookie_name in resp.headers.get("Set-Cookie", "").split(","):
                    if cookie_pattern.lower().replace("*", "") in cookie_name.lower():
                        confidence += 0.3
                        detected_by = f"cookie:{cookie_name.strip()[:50]}"
                        break

            for pattern in signatures["body_patterns"]:
                if re.search(pattern, resp.text, re.IGNORECASE):
                    confidence += 0.3
                    detected_by = f"body:{pattern}"
                    break

            if confidence >= 0.4:
                return WAFInfo(
                    name=waf_name,
                    confidence=min(confidence, 1.0),
                    detected_by=detected_by,
                    bypass_techniques=self._get_bypass_techniques(waf_name),
                )

        if resp.status_code in [403, 406, 429, 503]:
            return WAFInfo(
                name="Unknown WAF",
                confidence=0.3,
                detected_by=f"status:{resp.status_code}",
            )

        return WAFInfo(name="None", confidence=0.0)

    def _make_simple_response(self, resp_obj) -> object:
        """Convert requests.Response to simple object with needed attributes."""
        class SimpleResp:
            def __init__(self, r):
                self.status_code = r.status_code
                self.headers = dict(r.headers)
                self.text = r.text
        return SimpleResp(resp_obj)

